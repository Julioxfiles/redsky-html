<h1>Button</h1>

<p>
The Button component generates a semantic HTML button element
used for user interactions and form actions.
</p>


<h2>Methods</h2>


<h3>type()</h3>

<p>
Defines the button type.
</p>

<ul>
    <li>button</li>
    <li>submit</li>
    <li>reset</li>
</ul>


<h3>disabled()</h3>

<p>
Enables or disables the button.
</p>


<h3>name()</h3>

<p>
Sets the button name attribute.
</p>


<h3>value()</h3>

<p>
Sets the button value attribute.
</p>


