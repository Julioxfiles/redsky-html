/**
 * Renders a collection of Lucide icons grouped by category.
 *
 * @param string $title Category title.
 * @param array<int, string> $icons Icon names.
 * @param int $size Icon dimensions in pixels.
 *
 * @return void
 */
/**
 * Renders a collection of Lucide icons grouped by category.
 *
 * @param string $title Category title.
 * @param array<int, string> $icons Icon names.
 * @param int $size Icon dimensions in pixels.
 * @param array<int, string> $colors Available icon colors.
 *
 * @return void
 */
function renderIconCategory(
    string $title,
    array $icons,
    int $size,
    array $colors
): void {
    echo '<section class="icon-category">';

    echo '<h3 class="icon-category-title">'
        . htmlspecialchars($title, ENT_QUOTES, 'UTF-8')
        . '</h3>';

    echo '<div class="icon-list">';

    foreach ($icons as $index => $name) {
        try {
            $icon = new Icon($name);

            $color = $colors[$index % count($colors)];

            $icon->size($size);
            $icon->color($color);
            $icon->label($name);

            echo '<span'
                . ' class="icon-item"'
                . ' data-tooltip="'
                . htmlspecialchars($name, ENT_QUOTES, 'UTF-8')
                . '"'
                . ' tabindex="0"'
                . '>';

            echo $icon->render();

            echo '</span>';

        } catch (\Throwable $exception) {
            continue;
        }
    }

    echo '</div>';
    echo '</section>';
}

