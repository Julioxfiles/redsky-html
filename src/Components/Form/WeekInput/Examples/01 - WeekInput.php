<?php

declare(strict_types=1);

use RedSky\Html\Components\Form\WeekInput\WeekInput;

$week = new WeekInput('week');

/*
|--------------------------------------------------------------------------
| Current week
|--------------------------------------------------------------------------
*/

$week->current();
/*
|--------------------------------------------------------------------------
| Selectable week range
|--------------------------------------------------------------------------
*/

$week->between(
    '2026-W01',
    '2026-W52'
);

/*
|--------------------------------------------------------------------------
| Additional HTML attributes
|--------------------------------------------------------------------------
*/

$week->attribute(
    'id',
    'week-input'
);

$week->class(
    'week-input'
);


echo $week;

